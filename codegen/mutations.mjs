// Emits `schema/mutations.graphql`: every mutation this binary sends.
//
// These were `format!()` templates in src/api.rs, which put them out of reach
// of both checks. `generate.mjs` validates the documents in `schema/`, and
// `check-live.mjs` validates them again against findopera.com; a string built
// in Rust is seen by neither. That is not a hypothetical gap. `undelete*`
// changed from returning a Boolean to returning the record, which made every
// restore this CLI sent invalid, and nothing went red -- the same way
// `createAccessToken` gaining a required argument went unnoticed until it was
// moved into `token.graphql`.
//
// So they are written out here instead, one named operation per type and verb,
// and validated with everything else.

import { getNamedType, isCompositeType } from "graphql";
import { table } from "./crud.mjs";

/**
 * What a mutation must select, if anything.
 *
 * A field returning a record refuses an empty selection, and a field returning
 * a Boolean refuses a selection. Which one a mutation is has changed underneath
 * this CLI once already, so it is read off the schema rather than written down:
 * `delete*` returns a Boolean today and `undelete*` used to.
 *
 * `id` is what every caller wants -- a create reports the id it was given, and
 * a merge the id that survived -- and it is the least that can be asked for.
 */
function selection(schema, mutation, fields) {
  const field = schema.getMutationType().getFields()[mutation];
  if (!field) throw new Error(`the schema has no mutation \`${mutation}\``);
  if (!isCompositeType(getNamedType(field.type))) {
    // A Boolean refuses a selection, so asking for one would be an error
    // rather than an empty result.
    if (fields) {
      throw new Error(`${mutation} returns a scalar and cannot select fields`);
    }
    return "";
  }
  return ` { ${(fields ?? ["id"]).join(" ")} }`;
}

function operation(schema, name, variables, mutation, args, fields) {
  const declared = variables.map(([n, t]) => `$${n}: ${t}`).join(", ");
  const passed = args.map(([a, v]) => `${a}: $${v}`).join(", ");
  return (
    `mutation ${name}(${declared}) {\n` +
    `  ${mutation}(${passed})${selection(schema, mutation, fields)}\n}`
  );
}

export function mutations(schema, getOperations) {
  const out = [];
  out.push("# Every mutation this binary sends, bar the two that stand alone:");
  out.push("# `NewToken` in token.graphql and `Say` in feedback.graphql, which");
  out.push("# belong to a command rather than to a record.");
  out.push("#");
  out.push("# Generated by `codegen/mutations.mjs` from the schema and the type");
  out.push("# table. Do not edit; run `npm run generate`.");
  out.push("#");
  out.push("# Checked in and validated for the same reason `get.graphql` is: these");
  out.push("# are strings the binary sends, and a field that changed shape upstream");
  out.push("# should fail the build rather than somebody's edit.");
  out.push("");

  for (const t of table(schema, getOperations)) {
    // A type with a composite create always uses it, so only the one it
    // actually sends is written. Emitting both would validate a document this
    // CLI never sends and hide the one it does.
    if (t.composite) {
      const extras = t.composite.extras;
      out.push(
        operation(
          schema,
          `Add${t.graphql}`,
          [
            ["input", `${t.createInput}!`],
            ["justification", "String!"],
            ...extras.map((e) => [e.name, e.gql]),
          ],
          t.composite.mutation,
          [
            ["input", "input"],
            ["justification", "justification"],
            ...extras.map((e) => [e.name, e.name]),
          ],
        ),
      );
    } else {
      out.push(
        operation(
          schema,
          `Add${t.graphql}`,
          [
            ["input", `${t.createInput}!`],
            ["justification", "String!"],
          ],
          t.add,
          [
            ["input", "input"],
            ["justification", "justification"],
          ],
        ),
      );
    }

    out.push(
      operation(
        schema,
        `Edit${t.graphql}`,
        [
          ["id", "String!"],
          ["input", `${t.editInput}!`],
          ["justification", "String!"],
        ],
        t.update,
        [
          ["id", "id"],
          ["input", "input"],
          ["justification", "justification"],
        ],
      ),
    );

    // Only some types merge, and a type without one is not a gap: nothing
    // should be emitted for it, or the document would name a mutation the
    // schema does not have.
    if (t.merge) {
      out.push(
        operation(
          schema,
          `Merge${t.graphql}`,
          [
            ["id", "String!"],
            ["intoId", "String!"],
            ["justification", "String!"],
          ],
          t.merge,
          [
            ["id", "id"],
            ["intoId", "intoId"],
            ["justification", "justification"],
          ],
        ),
      );
    }

    for (const [verb, mutation] of [
      ["Restore", t.restore],
      ["Comment", t.comment],
      ["Remove", t.remove],
    ]) {
      out.push(
        operation(
          schema,
          `${verb}${t.graphql}`,
          [
            ["id", "String!"],
            ["justification", "String!"],
          ],
          mutation,
          [
            ["id", "id"],
            ["justification", "justification"],
          ],
        ),
      );
    }
  }

  // The two that join a recording to a UPC. They act on a pair rather than on
  // one record, so the table of types has nothing to hang them from and they
  // are named here rather than derived.
  out.push(
    operation(
      schema,
      "LinkRecordingUpc",
      [
        ["input", "LinkRecordingUpcInput!"],
        ["justification", "String!"],
      ],
      "linkRecordingToUpc",
      [
        ["input", "input"],
        ["justification", "justification"],
      ],
    ),
  );
  out.push(
    operation(
      schema,
      "UnlinkRecordingUpc",
      [
        ["recordingId", "String!"],
        ["upc", "String!"],
        ["justification", "String!"],
      ],
      "unlinkRecordingUpc",
      [
        ["recordingId", "recordingId"],
        ["upc", "upc"],
        ["justification", "justification"],
      ],
    ),
  );

  // Putting a recording in one of the viewer's own lists, and taking it out
  // again. Hand-named for the same reason the pair above is, and for a second
  // one: these take no `justification`. Every catalog mutation does, because
  // every catalog mutation edits something shared; a list is one person's, and
  // the type table's shape has nowhere to put a mutation without one.
  //
  // `entryCount` comes back because the useful thing to say afterwards is how
  // big the list now is, `name` because the caller passed an id and a number
  // is not what anybody calls their list, and `url` because that is what the
  // settings take and so what somebody setting this up needs to copy.
  for (const [name, mutation] of [
    ["AddRecordingToCollection", "addRecordingToCollection"],
    ["RemoveRecordingFromCollection", "removeRecordingFromCollection"],
  ]) {
    out.push(
      operation(
        schema,
        name,
        [
          ["collectionId", "Int!"],
          ["recordingId", "Int!"],
        ],
        mutation,
        [
          ["collectionId", "collectionId"],
          ["recordingId", "recordingId"],
        ],
        ["id", "name", "entryCount", "url"],
      ),
    );
  }

  // Starting a list, and replacing what one holds outright.
  //
  // `setCollectionRecordings` is the wholesale path: "for a caller that has a
  // whole list in hand and wants it to match", which is what anything walking
  // a library and reporting what it found has. It is also the one mutation
  // here that destroys -- an empty list clears the collection -- so the
  // command in front of it is the place to be careful, not this file.
  out.push(
    operation(
      schema,
      "CreateCollection",
      [["name", "String!"]],
      "createCollection",
      [["name", "name"]],
      ["id", "name", "entryCount", "url"],
    ),
  );
  out.push(
    operation(
      schema,
      "SetCollectionRecordings",
      [
        ["collectionId", "Int!"],
        ["recordingIds", "[Int!]!"],
      ],
      "setCollectionRecordings",
      [
        ["collectionId", "collectionId"],
        ["recordingIds", "recordingIds"],
      ],
      ["id", "name", "entryCount", "url"],
    ),
  );

  out.push(
    operation(
      schema,
      "RenameCollection",
      [
        ["id", "Int!"],
        ["name", "String!"],
      ],
      "renameCollection",
      [
        ["id", "id"],
        ["name", "name"],
      ],
      ["id", "name", "entryCount", "url"],
    ),
  );
  // Returns a Boolean, so it selects nothing -- and unlike `delete<Type>`
  // there is no `undelete` beside it. Nothing here can put a list back.
  out.push(
    operation(
      schema,
      "DeleteCollection",
      [["id", "Int!"]],
      "deleteCollection",
      [["id", "id"]],
    ),
  );

  return out.join("\n") + "\n";
}
